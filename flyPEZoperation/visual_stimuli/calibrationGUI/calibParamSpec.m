function spec = calibParamSpec()
%CALIBPARAMSPEC The 14 editable calibration values, in suggested order.
%   One struct per value: key, group, units, step, desc, up, down.
%   desc is copied from the comments in projectorCalibration3000_v3.m.
%   up/down say what happens when the value is raised/lowered. Text ending in
%   "(from code)" was derived from reading v3's maths, not from its comments;
%   "(not stated in v3)" means neither source gave a direction yet.
%   stimRefROI is split into stimRefX/stimRefY; see calibParamsFromValues.
S = @(key,group,units,step,desc,up,down) struct('key',key,'group',group,...
    'units',units,'step',step,'desc',desc,'up',up,'down',down);
ns = '(not stated in v3 - confirm on the rig)';
spec = [
S('atMirPlane2projector','1 Crosshairs','inches',0.05,...
    'Measure the distance from the top of the mirror plane to the lens.',ns,ns)
S('sphereCircumference','2 10-cm lines','mm',0.5,...
    'Using tailor''s measuring tape, empirically determine the circimference of the dome.',ns,ns)
S('zoomTheta','2 10-cm lines','degrees',0.05,...
    ['Adjust until the scale of the top projection aligns with the 10mm marks ' ...
    'on the measuring tape. Bigger numbers reduce the spacing between the lines.'],...
    'Lines move closer together.','Lines spread further apart.')
S('sphDropDiff','2 10-cm lines','',0.005,...
    ['Adjust until the bottom projection dashed lines align with the two top ' ...
    'projection dashed lines. When the dashed lines align, the solid ones ' ...
    'should all line up with the 10-mm marks. If not, slightly adjust the ' ...
    'zoom and try again.'],...
    'Bottom lines move lower.','Bottom lines move higher.')
S('whRatioAdjust','3 Transition ring','',0.0005,...
    'Adjust until the sides align.',...
    'Mirror reflection goes down on the sides relative to the top reflection.',...
    'Mirror reflection goes up on the sides relative to the top reflection.')
S('topThreshFactor','3 Transition ring','',0.005,...
    ['Position the transition from top-projection to mirror-projection to ' ...
    'the edge of the mirror.'],ns,ns)
S('stimRefX','3 Transition ring','pixels',1,...
    'Reference flicker window, x1 from the left of the screen.',...
    'Window moves right (from code).','Window moves left (from code).')
S('stimRefY','3 Transition ring','pixels',1,...
    'Reference flicker window, y1 from the top of the screen.',...
    'Window moves down (from code).','Window moves up (from code).')
S('hypSkewTB','4 Blended ring','',0.001,...
    ['Fine-tuning to skew diagonally. Positive numbers rock the ' ...
    'mirror-reflected ring towards the camera.'],...
    'Mirror ring rocks towards the camera.','Mirror ring rocks away from the camera.')
S('hypSkewLR','4 Blended ring','',0.001,...
    ['Fine-tuning to skew diagonally. Positive numbers rock the ' ...
    'mirror reflected ring to the right from the perspective of the camera.'],...
    'Mirror ring rocks to the right (camera view).','Mirror ring rocks to the left (camera view).')
S('hypTwistA','4 Blended ring','',0.005,...
    'Right side twist. Positive numbers twist top or right. Effect grows as value^2 (from code).',...
    'Top-right pushed out, bottom-right pulled in (from code).',...
    'Top-right pulled in, bottom-right pushed out (from code).')
S('hypTwistB','4 Blended ring','',0.005,...
    'Left side twist. Positive numbers twist top or right. Effect grows as value^2 (from code).',...
    'Top-left pushed out, bottom-left pulled in (from code).',...
    'Top-left pulled in, bottom-left pushed out (from code).')
S('hypTwistC','4 Blended ring','',0.005,...
    'Bottom twist. Positive numbers twist top or right. Effect grows as value^2 (from code).',...
    'Bottom-left pushed out, bottom-right pulled in (from code).',...
    'Bottom-left pulled in, bottom-right pushed out (from code).')
S('hypTwistD','4 Blended ring','',0.005,...
    'Top twist. Positive numbers twist top or right. Effect grows as value^2 (from code).',...
    'Top-left pushed out, top-right pulled in (from code).',...
    'Top-left pulled in, top-right pushed out (from code).')
];
end
